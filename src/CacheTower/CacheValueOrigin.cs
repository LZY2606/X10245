using System;

namespace CacheTower;

/// <summary>
/// Describes where the value returned from an opt-in stale-while-revalidate read originated.
/// </summary>
/// <remarks>
/// The origin combines <em>which</em> cache layer (or the value factory) provided the value with
/// <em>whether</em> that value was still fresh, allowing callers to distinguish between
/// memory layer, backing layer, stale and factory sourced results without inspecting the cache state themselves.
/// </remarks>
public enum CacheValueOrigin
{
	/// <summary>
	/// The value was returned from the first (highest priority) cache layer and had not expired.
	/// </summary>
	MemoryFresh,
	/// <summary>
	/// The value was returned from a lower (backing) cache layer and had not expired.
	/// </summary>
	BackingFresh,
	/// <summary>
	/// The value had expired but was still within the stale-while-revalidate window and was served from the first (highest priority) cache layer.
	/// </summary>
	MemoryStale,
	/// <summary>
	/// The value had expired but was still within the stale-while-revalidate window and was served from a lower (backing) cache layer.
	/// </summary>
	BackingStale,
	/// <summary>
	/// No servable value existed, so the value factory was invoked to generate the value.
	/// </summary>
	Factory,
}

/// <summary>
/// A receipt describing the origin of a value returned from an opt-in stale-while-revalidate read.
/// </summary>
/// <remarks>
/// The receipt is diagnostic only - it is produced after the value has been resolved and never influences the value returned.
/// </remarks>
/// <param name="Origin">Where the returned value originated.</param>
/// <param name="LayerIndex">The zero-based index of the cache layer that provided the value, or <c>-1</c> when the value factory provided it.</param>
public readonly record struct CacheReadReceipt(CacheValueOrigin Origin, int LayerIndex)
{
	/// <summary>
	/// Whether the returned value was provided by a cache layer rather than the value factory.
	/// </summary>
	public bool IsFromCache => LayerIndex >= 0;

	/// <summary>
	/// Whether the returned value was provided by the value factory rather than a cache layer.
	/// </summary>
	public bool IsFromFactory => Origin == CacheValueOrigin.Factory;

	/// <summary>
	/// Whether the returned value had expired but was served because it was still within the stale-while-revalidate window.
	/// </summary>
	public bool IsStale => Origin is CacheValueOrigin.MemoryStale or CacheValueOrigin.BackingStale;

	/// <summary>
	/// Whether the returned value was provided by the first (highest priority) cache layer.
	/// </summary>
	public bool IsMemoryLayer => LayerIndex == 0;

	/// <summary>
	/// Whether the returned value was provided by a lower (backing) cache layer rather than the first.
	/// </summary>
	public bool IsBackingLayer => LayerIndex > 0;

	/// <inheritdoc/>
	public override string ToString() => $"CacheReadReceipt(Origin={Origin}, LayerIndex={LayerIndex})";
}

/// <summary>
/// The result of an opt-in stale-while-revalidate read, containing both the value and a <see cref="CacheReadReceipt"/> describing its origin.
/// </summary>
/// <typeparam name="T">The type of value in the result.</typeparam>
/// <param name="Value">The value resolved by the read.</param>
/// <param name="Receipt">The receipt describing where <paramref name="Value"/> originated.</param>
public readonly record struct CacheReadResult<T>(T? Value, CacheReadReceipt Receipt)
{
	/// <summary>
	/// Creates a receipt for a value served from the cache layer at <paramref name="layerIndex"/>.
	/// </summary>
	/// <param name="value">The value served to the caller.</param>
	/// <param name="layerIndex">The zero-based index of the cache layer that provided the value.</param>
	/// <param name="isStale">Whether the value had expired but was still within the stale-while-revalidate window.</param>
	internal static CacheReadResult<T> FromCache(T? value, int layerIndex, bool isStale)
	{
		var origin = (layerIndex, isStale) switch
		{
			(0, false) => CacheValueOrigin.MemoryFresh,
			(_, false) => CacheValueOrigin.BackingFresh,
			(0, true) => CacheValueOrigin.MemoryStale,
			(_, true) => CacheValueOrigin.BackingStale,
		};
		return new(value, new(origin, layerIndex));
	}

	/// <summary>
	/// Creates a receipt for a value generated by the value factory.
	/// </summary>
	/// <param name="value">The value generated by the value factory.</param>
	internal static CacheReadResult<T> FromFactory(T? value) => new(value, new(CacheValueOrigin.Factory, -1));

	/// <inheritdoc/>
	public override string ToString() => $"CacheReadResult({Value}, {Receipt})";
}
